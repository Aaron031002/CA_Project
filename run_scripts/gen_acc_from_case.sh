#!/bin/bash
# gen_acc_from_case.sh
#
# Generates new_code/test/small_mlp_Acc.cpp, the SystemC testbench for the
# small_mlp case. The accelerator in this project is a FIXED 2x2 mesh
# (4 cores, plain XY routing, no wraparound); the mesh size is built into
# the generated testbench and is not read from any file.
#
# Auto-discovered by new_code/test/CMakeLists.txt's file(GLOB "*_Acc.cpp").
#
# Usage (from any directory):
#   run_scripts/gen_acc_from_case.sh
#
# Output: new_code/test/small_mlp_Acc.cpp
# Build (from new_code/build/): cmake .. && make small_mlp_Acc
# Run (from the REPOSITORY ROOT -- file paths in the instructions and
# dram_map.yaml are relative to it):
#   new_code/build/bin/small_mlp_Acc <inst_dir> [<output_file> <expected_rows> <expected_cols>]

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

usage() {
    echo "Usage: $(basename "${BASH_SOURCE[0]}")   (takes no arguments)"
    exit 1
}

case "${1:-}" in
    -h|--help) usage ;;
esac
[ $# -eq 0 ] || usage

CONFIG_NAME="small_mlp"
PREFIX="$CONFIG_NAME"
MESH_W=2
MESH_H=2
TOPOLOGY="XY"
OUT_FILE="$REPO_ROOT/new_code/test/${PREFIX}_Acc.cpp"

mkdir -p "$(dirname "$OUT_FILE")"
echo "Generating $OUT_FILE (fixed ${MESH_W}x${MESH_H} ${TOPOLOGY} mesh)..."

cat > "$OUT_FILE" <<EOF
// ${PREFIX}_Acc.cpp ── SystemC testbench for the ${PREFIX} case on the
// fixed ${MESH_W}x${MESH_H} mesh accelerator (${TOPOLOGY} routing). The mesh size is
// built in; any acc_config.yaml in the case folder is ignored. Generated by
// run_scripts/gen_acc_from_case.sh -- do not edit by hand, re-run that
// script instead.
//
// Auto-discovered by new_code/test/CMakeLists.txt's file(GLOB "*_Acc.cpp")
// -- re-run \`cmake ..\` after (re)generating this file for the build
// target to appear.
//
// Build (from new_code/build/):
//   cmake .. && make ${PREFIX}_Acc
// Run (from the repository root -- file paths in the instructions and
// dram_map.yaml are relative to it):
//   new_code/build/bin/${PREFIX}_Acc <inst_dir> [<output_file> <expected_rows> <expected_cols>]

#ifndef SC_INCLUDE_DYNAMIC_PROCESSES   // CMake already defines it
#define SC_INCLUDE_DYNAMIC_PROCESSES
#endif
#include <systemc.h>

#include <cmath>
#include <cstdlib>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <memory>
#include <string>
#include <vector>

#include "Acc/acc_8x8.h"
#include "utils/busyState.h"

using namespace LLM_SIM_BUSY;

namespace fs = std::filesystem;

static int g_checks = 0, g_failures = 0;
static bool g_watchdog_fired = false;
static void chk(bool cond, const std::string& msg) {
    ++g_checks;
    if (!cond) {
        ++g_failures;
        std::cerr << "[FAIL] " << msg << "\\n";
    } else {
        std::cerr << "[ OK ] " << msg << "\\n";
    }
}

// The accelerator is fixed: ${MESH_W}x${MESH_H} cores, ${TOPOLOGY} routing.
static constexpr int kMeshWidth  = ${MESH_W};
static constexpr int kMeshHeight = ${MESH_H};

SC_MODULE(AccTB) {
    sc_clock      clk;
    Acc8x8<float> dut;
    sc_buffer<bool> start_buf;

    const sc_time watchdog_time;

    SC_HAS_PROCESS(AccTB);

    AccTB(sc_module_name nm, const std::string& inst_dir,
          int mesh_width, int mesh_height,
          sc_time wd = sc_time(2'000'000, SC_NS))
        : sc_module(nm),
          clk("clk", 1.0, SC_NS),
          dut("dut", inst_dir, "${TOPOLOGY}", true,
              inst_dir + "/dram_map.yaml", "", "",
              0, "",
              mesh_width, mesh_height),
          start_buf("start_buf"),
          watchdog_time(wd)
    {
        dut.clk(clk);
        dut.start(start_buf);

        SC_THREAD(drive_start);
        SC_THREAD(monitor_done);
        SC_THREAD(watchdog);
    }

    void drive_start() {
        start_buf.write(false);
        wait(2, SC_NS);
        std::cerr << "[TB] Asserting start at " << sc_time_stamp() << "\\n" << std::flush;
        start_buf.write(true);
    }

    // mc_done_buf alone only means MainCtrl's instruction loop has DISPATCHED
    // every instruction -- dispatching a DMA NoC recv/Array/Vector
    // instruction enqueues it into that unit's own FIFO and returns
    // immediately; it does not block until the unit actually finishes. The
    // correct condition additionally requires every unit's own busy channel
    // to report idle (same check MainCtrl::allUnitsIdle() itself performs
    // for LOCAL_SYNC, here checked from the testbench across all
    // dut.num_cores() cores).
    static bool unit_idle(Core<float>* c) {
        auto a = c->array_busy_ch.read();
        auto v = c->vec_busy_ch.read();
        auto d = c->dma_busy_ch.read();
        auto t = c->tmu_busy_ch.read();
        if (a && a->isBusy()) return false;
        if (v && v->isBusy()) return false;
        if (d && d->isBusy()) return false;
        if (t && t->isBusy()) return false;
        return true;
    }

    void monitor_done() {
        // Require the "all done + all idle" condition to hold for several
        // consecutive cycles (not just one instant) -- a core can dispatch
        // its last instruction (mc_done_buf -> true) and briefly look idle
        // one cycle before a just-arrived NoC packet's landing/consumption
        // ticks a unit busy again the next cycle.
        static constexpr int STABLE_CYCLES = 20;
        int stable = 0;
        while (stable < STABLE_CYCLES) {
            wait(clk.posedge_event());
            bool all = true;
            for (int i = 0; i < dut.num_cores(); ++i) {
                if (!dut.cores[i]->mc_done_buf.read() || !unit_idle(dut.cores[i])) {
                    all = false;
                    break;
                }
            }
            stable = all ? stable + 1 : 0;
        }
        const uint64_t total_cycles =
            static_cast<uint64_t>(sc_time_stamp() / sc_time(1, SC_NS));
        std::cerr << "[TB] All " << dut.num_cores() << " cores ("
                  << dut.mesh_width() << "x" << dut.mesh_height()
                  << " mesh) done at " << sc_time_stamp()
                  << " (" << total_cycles << " cycles)\\n" << std::flush;
        sc_stop();
    }

    void watchdog() {
        wait(watchdog_time);
        g_watchdog_fired = true;
        std::cerr << "[TB] WATCHDOG EXPIRED -- simulation did not finish in time!\\n" << std::flush;
        sc_stop();
    }
};

int sc_main(int argc, char* argv[]) {
    if (argc < 2) {
        std::cerr << "Usage: " << argv[0]
                   << " <inst_dir> [<output_file> <expected_rows> <expected_cols>]\\n";
        return 1;
    }
    std::string inst_dir = argv[1];
    if (!fs::exists(inst_dir)) {
        std::cerr << "[ERROR] Instruction directory not found: " << inst_dir << "\\n";
        return 1;
    }

    // DRAM file paths (instructions, dram_map.yaml) are opened relative to
    // the current directory, which must therefore be the repository root.
    if (!fs::is_directory("new_code/DRAM_sim/DRAM_data")) {
        std::cerr << "[ERROR] Run this from the repository root (the folder that contains "
                  << "new_code/ and run_scripts/): file paths in your instructions and "
                  << "dram_map.yaml are relative to it. Current directory: "
                  << fs::current_path().string() << "\\n";
        return 1;
    }

    const int mesh_width = kMeshWidth, mesh_height = kMeshHeight;
    if (fs::exists(inst_dir + "/acc_config.yaml")) {
        std::cerr << "[TB] Note: " << inst_dir << "/acc_config.yaml is ignored -- "
                  << "the mesh is fixed at " << mesh_width << "x" << mesh_height << "\\n";
    }

    std::cerr << "[TB] Acc mesh test (${PREFIX}, fixed mesh: "
              << mesh_width << "x" << mesh_height << " ${TOPOLOGY})\\n";
    std::cerr << "[TB] inst_dir: " << inst_dir << "\\n" << std::flush;

    // Check the case files before building the accelerator: its constructor
    // already reads dram_map.yaml, so a missing file would otherwise surface as
    // an uncaught SystemC exception instead of a clear message.
    if (!fs::exists(inst_dir + "/dram_map.yaml")) {
        std::cerr << "[ERROR] Missing DRAM map: " << inst_dir << "/dram_map.yaml\\n";
        return 1;
    }
    for (int id = 0; id < mesh_width * mesh_height; ++id) {
        std::string f = inst_dir + "/core_" + std::to_string(id) + "_insts.txt";
        if (!fs::exists(f)) {
            std::cerr << "[ERROR] Missing instruction file: " << f << "\\n";
            return 1;
        }
        // A UTF-8 byte-order mark (e.g. "UTF-8 with BOM" from a Windows
        // editor, or Python's encoding="utf-8-sig") would make the first
        // line an unknown opcode.
        char bom[3] = {0, 0, 0};
        std::ifstream(f, std::ios::binary).read(bom, 3);
        if (bom[0] == '\\xEF' && bom[1] == '\\xBB' && bom[2] == '\\xBF') {
            std::cerr << "[ERROR] " << f << " starts with a UTF-8 byte-order mark (BOM). "
                      << "Save it as plain UTF-8 without BOM (in Python: encoding=\\"utf-8\\").\\n";
            return 1;
        }
    }

    std::unique_ptr<AccTB> tb;
    try {
        tb.reset(new AccTB("tb", inst_dir, mesh_width, mesh_height));
    } catch (const std::exception& e) {
        std::cerr << "[ERROR] Could not read the case files in " << inst_dir
                  << " (check dram_map.yaml): " << e.what() << "\\n";
        return 1;
    }

    sc_start();

    // A watchdog stop must fail the run even if an older output file from a
    // previous run is still on disk and would pass the checks below.
    chk(!g_watchdog_fired, "Simulation finished before the watchdog");

    if (argc >= 5) {
        std::string output_file = argv[2];
        int rows = std::atoi(argv[3]);
        int cols = std::atoi(argv[4]);
        std::ifstream f(output_file, std::ios::binary);
        chk(f.is_open(), "Output file exists: " + output_file);
        if (f.is_open()) {
            std::vector<float> data(static_cast<size_t>(rows) * cols);
            f.read(reinterpret_cast<char*>(data.data()),
                   static_cast<std::streamsize>(data.size() * sizeof(float)));
            chk(static_cast<size_t>(f.gcount()) == data.size() * sizeof(float),
                "Output file size matches expected " + std::to_string(rows) + "x" + std::to_string(cols));
            bool all_finite = true;
            for (float v : data) if (!std::isfinite(v)) { all_finite = false; break; }
            chk(all_finite, "Output values are all finite");
        }
    }

    std::cerr << "\\n[TB] " << g_checks << " checks, " << g_failures << " failures\\n";
    return g_failures == 0 ? 0 : 1;
}
EOF

echo "Wrote $OUT_FILE"
